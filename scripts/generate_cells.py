"""Derive capability cells from measurement artifacts and compare with the published ones.

    uv run python scripts/generate_cells.py --check     report drift, exit 1 on any
    uv run python scripts/generate_cells.py             print the derived cells

Until the capability files are generated by the build, this is the audit: every
published cell that the artifacts can derive must agree with the derivation, and every
disagreement is either a hand-transcription error or a gap in the rules. Both are
worth knowing.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from mcp_mirror.cells import derive_harness_cells, derive_result_cells, derive_snapshot  # noqa: E402

SNAPSHOTS = [ROOT / "data", *sorted((ROOT / "data" / "specs").glob("*/"))]


def published_cells(
    snapshot: Path,
) -> tuple[dict[str, dict[str, str]], dict[str, list[str]], dict[str, str]]:
    """Cells as last built into data/fulldata, which is what the site serves.

    Overlays carry no cells, so the comparison that matters is between a fresh
    derivation and the committed build: a difference means the build is stale.
    """
    frameworks = json.loads((snapshot / "frameworks.json").read_text())
    built = json.loads((ROOT / "data" / "fulldata" / f"data-{frameworks['mcp_spec']}.json").read_text())
    aliases = {
        agent_id: agent["aliases_of"]
        for agent_id, agent in built["agents"].items()
        if agent.get("aliases_of")
    }
    out: dict[str, dict[str, str]] = {}
    dependent: dict[str, list[str]] = {}
    for capability in built["data"].values():
        if capability.get("measurement_state") == "not_measured":
            continue
        out[capability["id"]] = {
            agent: next(iter(cells.values())).split()[0]
            for agent, cells in capability["stats"].items()
        }
        # An alias is checked against its source below, not against the derivation.
        dependent[capability["id"]] = sorted(
            a for a in capability.get("boundary_dependent") or [] if a not in aliases
        )
    return out, dependent, aliases


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    drift = 0
    covered = 0
    for snapshot in SNAPSHOTS:
        if not (snapshot / "capabilities").exists():
            continue
        derived = derive_snapshot(snapshot)
        published, published_dependent, aliases = published_cells(snapshot)
        _result_cells, derived_dependent = derive_result_cells(snapshot)
        label = snapshot.relative_to(ROOT)
        print(f"\n## {label}")
        for capability_id, agents in derived_dependent.items():
            have = published_dependent.get(capability_id)
            if have is not None and sorted(agents) != have:
                drift += 1
                print(
                    f"  DRIFT {capability_id:<26} boundary_dependent published={have} "
                    f"derived={sorted(agents)}"
                )
        for capability_id in sorted(derived):
            row = derived[capability_id]
            if capability_id not in published:
                print(f"  {capability_id}: derivable but not published")
                if not arguments.check:
                    for agent, cell in sorted(row.items()):
                        print(f"    {agent:<14} {cell.code}  [{cell.instrument}] {'; '.join(cell.evidence[:2])}")
                continue
            for agent, cell in sorted(row.items()):
                covered += 1
                have = published[capability_id].get(agent)
                if have == cell.code:
                    if not arguments.check:
                        print(f"  {capability_id:<26} {agent:<14} {cell.code}")
                    continue
                drift += 1
                evidence = "; ".join(cell.evidence[:3])
                print(
                    f"  DRIFT {capability_id:<26} {agent:<14} published={have} "
                    f"derived={cell.code}  [{cell.instrument}] {evidence}"
                )
        for capability_id, row in sorted(published.items()):
            for alias, source in sorted(aliases.items()):
                if row.get(alias) != row.get(source):
                    drift += 1
                    print(
                        f"  DRIFT {capability_id:<26} {alias:<14} published={row.get(alias)} "
                        f"but its source {source} publishes {row.get(source)}"
                    )
    harness_dir = ROOT / "data" / "harnesses"
    built_harnesses = ROOT / "data" / "fulldata" / "harnesses.json"
    if harness_dir.is_dir():
        print("\n## data/harnesses")
        published = json.loads(built_harnesses.read_text())["data"] if built_harnesses.exists() else {}
        for capability_id, row in sorted(derive_harness_cells(harness_dir).items()):
            for agent, cell in sorted(row.items()):
                covered += 1
                have = next(iter(((published.get(capability_id) or {}).get("stats", {}).get(agent) or {"": "-"}).values()))
                have_value = (published.get(capability_id) or {}).get("values", {}).get(agent)
                if have.split()[0] == cell.code and have_value == cell.value:
                    if not arguments.check:
                        print(f"  {capability_id:<34} {agent:<14} {cell.code}")
                    continue
                drift += 1
                print(
                    f"  DRIFT {capability_id:<34} {agent:<14} published={have} {have_value!r} "
                    f"derived={cell.code} {cell.value!r}  [{cell.instrument}] {'; '.join(cell.evidence[:2])}"
                )
    print(f"\n{covered} cells derivable, {drift} disagree with the published data")
    return 1 if (arguments.check and drift) else 0


if __name__ == "__main__":
    raise SystemExit(main())
