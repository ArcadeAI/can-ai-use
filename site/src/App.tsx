const STAR_STORAGE_KEY = "mcpMirrorStars";

function useRoute(): Route {
  const [route, setRoute] = useState(() => routeFromHash(window.location.hash));

  useEffect(() => {
    const onHashChange = () => {
      setRoute(routeFromHash(window.location.hash));
      window.scrollTo({top: 0, behavior: "instant"});
    };
    // Back across a ?spec= change is a popstate with no hashchange, so listen for both.
    window.addEventListener("hashchange", onHashChange);
    window.addEventListener("popstate", onHashChange);
    return () => {
      window.removeEventListener("hashchange", onHashChange);
      window.removeEventListener("popstate", onHashChange);
    };
  }, []);

  return route;
}

function readStars(): string[] {
  try {
    return JSON.parse(localStorage.getItem(STAR_STORAGE_KEY) ?? "[]") as string[];
  } catch {
    return [];
  }
}

