/** What a framework cell's colour means, under the search bar on every page that shows one. */
function SupportLegend() {
  return (
    <section className="site-shell support-legend" aria-label="Legend">
      <ul>
        <li><i className="support-y" /> Present at capture boundary</li>
        <li><i className="support-a" /> Changed or retained elsewhere</li>
        <li><i className="support-n" /> Dropped during adaptation</li>
        <li><i className="support-x" /> Adapter cannot negotiate this revision</li>
        <li><i className="support-u" /> Not yet measured</li>
      </ul>
    </section>
  );
}

// The routes whose cells and bars use the framework colours; the agents pages carry their own legend.
const LEGEND_ROUTES = new Set(["index", "frameworks", "capability", "framework", "stats"]);

export default function App() {
  const inlineSpecIndex = window.__MCP_MIRROR_SPEC_INDEX__ ?? null;
  const requestedSpec = new URLSearchParams(window.location.search).get("spec");
  const initialSpec =
    (inlineSpecIndex
      ? initialSpecFor(
          inlineSpecIndex,
          requestedSpec,
          routeFromHash(window.location.hash),
        )
      : undefined) ??
    window.__MCP_MIRROR_DATA__?.mcp_spec ??
    requestedSpec ??
    "";
  const [specIndex, setSpecIndex] = useState<SpecIndex | null>(inlineSpecIndex);
  const [selectedSpec, setSelectedSpec] = useState(initialSpec);
  const [loadedDatabase, setDatabase] = useState<MirrorDatabase | null>(
    () =>
      window.__MCP_MIRROR_DATASETS__?.[initialSpec] ??
      window.__MCP_MIRROR_DATA__ ??
      null,
  );
  const database = useMemo(
    () =>
      loadedDatabase &&
      visibleDatabase(loadedDatabase, previewRequested(window.location.search)),
    [loadedDatabase],
  );
  const [loadError, setLoadError] = useState<string | null>(null);
  const [query, setQuery] = useState("");
  const [resultsMode, setResultsMode] = useState<ResultsMode>("tables");
  const [gridMode, setGridMode] = useState<GridMode>("support");
  const [stars, setStars] = useState<string[]>(readStars);
  const route = useRoute();
  const harnesses = useHarnessData(specIndex);

  useEffect(() => {
    if (specIndex) {
      return;
    }
    const controller = new AbortController();
    fetch("./data/specs.json", {signal: controller.signal})
      .then((response) => {
        if (!response.ok) {
          throw new Error(`Protocol index returned HTTP ${response.status}`);
        }
        return response.json() as Promise<SpecIndex>;
      })
      .then((index) => {
        const requested = new URLSearchParams(window.location.search).get("spec");
        const nextSpec = initialSpecFor(
          index,
          requested,
          routeFromHash(window.location.hash),
        );
        setSpecIndex(index);
        setSelectedSpec(nextSpec);
      })
      .catch((error: unknown) => {
        if (error instanceof DOMException && error.name === "AbortError") {
          return;
        }
        setLoadError(error instanceof Error ? error.message : "Unknown error");
      });
    return () => controller.abort();
  }, [specIndex]);

  useEffect(() => {
    if (!specIndex || !selectedSpec || database?.mcp_spec === selectedSpec) {
      return;
    }
    const entry = specIndex.specs.find((candidate) => candidate.id === selectedSpec);
    if (!entry) {
      setSelectedSpec(specIndex.default_spec);
      return;
    }
    const inline = window.__MCP_MIRROR_DATASETS__?.[entry.id];
    if (inline) {
      setDatabase(inline);
      return;
    }

    const controller = new AbortController();
    setLoadError(null);
    fetch(`./data/${entry.file}`, {signal: controller.signal})
      .then((response) => {
        if (!response.ok) {
          throw new Error(`Support data returned HTTP ${response.status}`);
        }
        return response.json() as Promise<MirrorDatabase>;
      })
      .then(setDatabase)
      .catch((error: unknown) => {
        if (error instanceof DOMException && error.name === "AbortError") {
          return;
        }
        setLoadError(error instanceof Error ? error.message : "Unknown error");
      });
    return () => controller.abort();
  }, [database?.mcp_spec, selectedSpec, specIndex]);

  // Back and Forward restore an entry's URL, ?spec= included, so the snapshot follows it;
  // otherwise the page keeps showing the revision chosen on a later entry.
  useEffect(() => {
    if (!specIndex) {
      return;
    }
    const onPopState = () => {
      setSelectedSpec(
        initialSpecFor(
          specIndex,
          new URLSearchParams(window.location.search).get("spec"),
          routeFromHash(window.location.hash),
        ),
      );
    };
    window.addEventListener("popstate", onPopState);
    return () => window.removeEventListener("popstate", onPopState);
  }, [specIndex]);

  useEffect(() => {
    if (!database) {
      return;
    }
    const capability =
      route.name === "capability"
        ? database.data[route.capabilityId]
        : undefined;
    const framework =
      route.name === "framework" ? database.agents[route.frameworkId] : undefined;
    const agent =
      route.name === "agent" ? harnesses.data?.agents[route.agentId] : undefined;
    const behaviour =
      route.name === "agentRow" ? harnesses.data?.data[route.rowId] : undefined;
    document.title = capability
      ? `${capability.title.replaceAll("`", "")} | Can AI use`
      : framework
        ? `${framework.name} MCP support | Can AI use`
        : agent
          ? `${agent.name} on the wire | Can AI use`
          : behaviour
            ? `${behaviour.title} | Can AI use`
            : `${
              route.name === "index"
                ? "Frameworks and agents, measured"
                : route.name === "frameworks"
                  ? "MCP capability support"
                : route.name === "stats"
                  ? "Capability statistics"
                  : isAgentsRoute(route)
                    ? "Agents on the wire"
                    : route.name
            } | Can AI use`;
  }, [database, harnesses.data, route]);

  // On a framework page the snapshot is always written into the URL, because without
  // one that page opens on the newest snapshot the framework reaches, not the default.
  const changeSpec = (value: string) => {
    if (!specIndex?.specs.some((entry) => entry.id === value)) {
      return;
    }
    const url = new URL(window.location.href);
    if (value === specIndex.default_spec && route.name !== "framework") {
      url.searchParams.delete("spec");
    } else {
      url.searchParams.set("spec", value);
    }
    window.history.replaceState(
      null,
      "",
      `${url.pathname}${url.search}${url.hash}`,
    );
    if (value !== selectedSpec) {
      setSelectedSpec(value);
      setDatabase(window.__MCP_MIRROR_DATASETS__?.[value] ?? null);
    }
    setLoadError(null);
  };

  // Arriving on a framework page with no ?spec= picks the snapshot it reaches; choosing
  // one in the selector writes ?spec=, so this never overrides the reader's choice.
  const frameworkRouteId = route.name === "framework" ? route.frameworkId : null;
  useEffect(() => {
    if (
      !specIndex ||
      frameworkRouteId === null ||
      new URLSearchParams(window.location.search).has("spec")
    ) {
      return;
    }
    const target = initialSpecFor(specIndex, null, {
      name: "framework",
      frameworkId: frameworkRouteId,
    });
    if (target !== specIndex.default_spec || target !== selectedSpec) {
      changeSpec(target);
    }
  }, [frameworkRouteId, specIndex]);

  const allCapabilities = useMemo(
    () => (database ? shownCapabilities(database) : []),
    [database],
  );
  const filteredCapabilities = useMemo(
    () =>
      allCapabilities.filter((capability) =>
        matchesCapability(capability, query),
      ),
    [allCapabilities, query],
  );
  // The search covers both measured sections; with no query the list is empty, so
  // the result count stays the capability count until someone types.
  const filteredBehaviours = useMemo(
    () =>
      query.trim() && harnesses.data
        ? Object.values(harnesses.data.data).filter((row) => matchesHarnessRow(row, query))
        : [],
    [harnesses.data, query],
  );

  if (loadError) {
    return (
      <div className="load-state">
        <Card className="load-card">
          <Card.Header>
            <Card.Title>Support data could not be loaded</Card.Title>
            <Card.Description>{loadError}</Card.Description>
          </Card.Header>
          <Card.Content>
            <p>
              Run <code>npm run dev</code> for local development or{" "}
              <code>npm run build</code> to regenerate the published site.
            </p>
          </Card.Content>
        </Card>
      </div>
    );
  }

  if (!database) {
    return (
      <div className="load-state" role="status">
        <Spinner size="lg" />
        <span>Loading measured support data</span>
      </div>
    );
  }

  const capability =
    route.name === "capability"
      ? database.data[route.capabilityId]
      : undefined;

  const onSearchChange = (value: string) => {
    setQuery(value);
    if (route.name !== "index") {
      window.location.hash = "#/";
    }
  };

  const toggleStar = (capabilityId: string) => {
    setStars((current) => {
      const next = current.includes(capabilityId)
        ? current.filter((id) => id !== capabilityId)
        : [...current, capabilityId];
      localStorage.setItem(STAR_STORAGE_KEY, JSON.stringify(next));
      return next;
    });
  };

  const resetHome = () => {
    setQuery("");
    if (window.location.hash !== "#/") {
      window.location.hash = "#/";
    } else {
      window.scrollTo({top: 0, behavior: "instant"});
    }
  };

  // A tab clears the search, since results only show on the home page; clicking the
  // tab already open scrolls to the top, as the wordmark does for home.
  const navigate = (hash: string) => {
    setQuery("");
    if (window.location.hash === hash) {
      window.scrollTo({top: 0, behavior: "instant"});
    }
  };

  return (
    <div className="site">
      <a className="skip-link" href="#main-content">
        Skip to content
      </a>
      <SiteHeader database={database} route={route} onNavigate={navigate} />
      <SearchHero
        query={query}
        resultCount={filteredCapabilities.length + filteredBehaviours.length}
        showSpec={!isAgentsRoute(route)}
        onChange={onSearchChange}
        onHomeReset={resetHome}
        specIndex={specIndex}
        selectedSpec={selectedSpec}
        onSpecChange={changeSpec}
        gridMode={gridMode}
        onGridModeChange={setGridMode}
      />
      {LEGEND_ROUTES.has(route.name) ? <SupportLegend /> : null}

      {route.name === "index" ? (
        <HomePage
          key={database.mcp_spec}
          capabilities={filteredCapabilities}
          database={database}
          harnesses={harnesses.data}
          behaviours={filteredBehaviours}
          query={query}
          resultsMode={resultsMode}
          onResultsModeChange={setResultsMode}
          stars={stars}
          onToggleStar={toggleStar}
          gridMode={gridMode}
          onGridModeChange={setGridMode}
          specIndex={specIndex}
        />
      ) : null}

      {route.name === "frameworks" ? (
        <FrameworksPage
          key={database.mcp_spec}
          capabilities={allCapabilities}
          database={database}
        />
      ) : null}

      {route.name === "capability" && capability ? (
        <CapabilityPage
          key={database.mcp_spec}
          capability={capability}
          database={database}
          starred={stars.includes(capability.id)}
          onToggleStar={() => toggleStar(capability.id)}
          gridMode={gridMode}
          onGridModeChange={setGridMode}
          specIndex={specIndex}
        />
      ) : null}

      {route.name === "capability" && !capability ? (
        <main className="site-shell page-main" id="main-content">
          <Card>
            <Card.Header>
              <Card.Title>Capability not found</Card.Title>
              <Card.Description>
                This measurement may have moved or is not published.
              </Card.Description>
            </Card.Header>
            <Card.Footer>
              <Link href="#/frameworks">Return to the frameworks</Link>
            </Card.Footer>
          </Card>
        </main>
      ) : null}

      {route.name === "framework" && database.agents[route.frameworkId] ? (
        <FrameworkPage
          key={`${database.mcp_spec}-${route.frameworkId}`}
          database={database}
          frameworkId={route.frameworkId}
          capabilities={allCapabilities}
          specIndex={specIndex}
        />
      ) : null}

      {route.name === "framework" && !database.agents[route.frameworkId] ? (
        <main className="site-shell page-main" id="main-content">
          <Card>
            <Card.Header>
              <Card.Title>Framework not found</Card.Title>
              <Card.Description>
                No framework with this id is published for MCP {database.mcp_spec}.
              </Card.Description>
            </Card.Header>
            <Card.Footer>
              <Link href="#/frameworks">Return to the frameworks</Link>
            </Card.Footer>
          </Card>
        </main>
      ) : null}

      {route.name === "changes" ? (
        <ChangesPage
          key={database.mcp_spec}
          capabilities={allCapabilities}
          database={database}
        />
      ) : null}
      {route.name === "stats" ? (
        <StatsPage
          key={database.mcp_spec}
          capabilities={allCapabilities}
          database={database}
        />
      ) : null}
      {route.name === "method" ? (
        <MethodPage key={database.mcp_spec} database={database} />
      ) : null}
      {route.name === "agents" ? (
        <AgentsPage data={harnesses.data} error={harnesses.error} />
      ) : null}
      {route.name === "agentRow" ? (
        <AgentRowPage
          key={route.rowId}
          data={harnesses.data}
          error={harnesses.error}
          rowId={route.rowId}
        />
      ) : null}
      {route.name === "agent" ? (
        <AgentPage
          key={route.agentId}
          data={harnesses.data}
          error={harnesses.error}
          agentId={route.agentId}
        />
      ) : null}

      <SiteFooter database={database} route={route} />
    </div>
  );
}
